// ─── App.jsx ─────────────────────────────────────────────────────────────────
// Main entry point for the SPARC research demo.
// Active app: main.jsx imports this file + styles.css.
//
// Sections:
//   1. Query Journey     — step-through simulation (illustrative, labeled)
//   2. Pareto Trade-off  — interactive scatter chart of the admission decision
//   3. SCALM vs SPARC    — live backend experiment runner + charts
//   4. Cache State       — living cache view with admission/eviction events
//   5. Demo Mode panel   — narration guide for the 10-12 min conference video
//
// All illustrative data is clearly distinguished from backend-measured results.

import React, { useMemo, useState, useEffect } from "react";
import {
  INITIAL_CACHE,
  DEMO_QUERIES,
  LLM_RESPONSES,
  SIMILARITY_MAP,
  SIMILARITY_THRESHOLD,
  CANDIDATE_ENTRIES,
  dominates,
  computeParetoFrontier,
  pruneByHypervolume,
  computeAdaptiveThreshold,
  classifyDomain,
} from "./cacheData";
import { ParetoScatterChart } from "./components/ParetoScatterChart";
import { ExperimentSection } from "./components/ExperimentSection";

// ─── STEP PIPELINE ──────────────────────────────────────────────────────────
const steps = [
  "idle",
  "embedding",
  "search",
  "decision",
  "inference",
  "evaluation",
  "pareto",
  "admission",
  "complete",
];

const STEP_LABELS = [
  { key: "embedding",  title: "Embed + Domain",         type: "SCALM+",   desc: "Query is vectorized; domain classified (general / medical / code / legal)" },
  { key: "search",     title: "Similarity Search",       type: "SCALM",    desc: "Find nearest cached entries by cosine similarity" },
  { key: "decision",   title: "Threshold Decision",      type: "PROPOSED", desc: "Adaptive threshold (domain + volatility aware) vs. SCALM fixed threshold" },
  { key: "inference",  title: "LLM Inference",           type: "Existing", desc: "On a miss, a new response is generated by the LLM" },
  { key: "evaluation", title: "Objective Evaluation",    type: "PROPOSED", desc: "Token-saving proxy and volatility score computed for candidate" },
  { key: "pareto",     title: "Pareto Skyline",          type: "PROPOSED", desc: "Non-dominated frontier computed over 2 objectives" },
  { key: "admission",  title: "Hypervolume Eviction",    type: "PROPOSED", desc: "Candidate admitted if non-dominated; budget enforced by hypervolume contribution" },
  { key: "complete",   title: "Cache Updated",           type: "CACHE",    desc: "Cache state updated; metrics recorded" },
];

// ─── METRIC CHIP ──────────────────────────────────────────────────────────────
function Metric({ label, value, unit = "" }) {
  return (
    <div className="metric">
      <span>{label}</span>
      <strong>{value}{unit}</strong>
    </div>
  );
}

// ─── VOLATILITY BAR ───────────────────────────────────────────────────────────
function VolatilityBar({ value }) {
  const pct = Math.round((value ?? 0) * 100);
  return (
    <div className="vol-bar-wrap" title={`Volatility: ${value?.toFixed(2)}`}>
      <span className="vol-bar" style={{ width: `${pct}%` }} />
    </div>
  );
}

// ─── NARRATION GUIDE ──────────────────────────────────────────────────────────
function NarrationGuide() {
  const stages = [
    { num: 1, title: "The problem", note: "Why semantic caches return stale answers — demo the CACHE HIT on a volatile query" },
    { num: 2, title: "A query enters", note: "Select a MISS query. Walk through embedding → search → threshold" },
    { num: 3, title: "SCALM's decision", note: "Show the fixed-threshold decision; explain TSR ranking" },
    { num: 4, title: "The volatility risk", note: "Show the volatility badge and explain why high savings ≠ safe to cache" },
    { num: 5, title: "Pareto frontier", note: "Click the Pareto Trade-off section; explain the two-objective scatter plot" },
    { num: 6, title: "SPARC's decision", note: "Show the adaptive threshold + dominance admission decision" },
    { num: 7, title: "Experimental evidence", note: "Switch to SCALM vs SPARC section; show the backend comparison chart" },
  ];
  return (
    <div className="narration-guide">
      <div className="narration-title">🎬 Demo Narration Guide — 10–12 min</div>
      <ul className="narration-steps">
        {stages.map((s) => (
          <li className="narration-step" key={s.num}>
            <span className="narration-step-num">{s.num}.</span>
            <span><strong>{s.title}:</strong> {s.note}</span>
          </li>
        ))}
      </ul>
    </div>
  );
}

// ─── MAIN APP ─────────────────────────────────────────────────────────────────
function App() {
  // ─── STATE ────────────────────────────────────────────────────────────────
  const [query, setQuery]                   = useState(DEMO_QUERIES[0].text);
  const [cache, setCache]                   = useState(INITIAL_CACHE);
  const [stepIndex, setStepIndex]           = useState(0);
  const [result, setResult]                 = useState(null);
  const [logs, setLogs]                     = useState([]);
  const [selectedDemoQuery, setSelectedDemoQuery] = useState(DEMO_QUERIES[0]);
  const [showDetailedMetrics, setShowDetailedMetrics] = useState(false);
  const [queryDomain, setQueryDomain]       = useState("general");
  const [adaptiveThreshold, setAdaptiveThreshold] = useState(SIMILARITY_THRESHOLD);
  const [systemMetrics, setSystemMetrics]   = useState(null);
  const [demoMode, setDemoMode]             = useState(false);
  const [theme]                             = useState("light");
  const [expandedEntry, setExpandedEntry]   = useState(null);
  const [showNarration, setShowNarration]   = useState(false);

  const step = steps[stepIndex];

  // Apply demo-mode class to body
  useEffect(() => {
    document.body.classList.toggle("demo-mode", demoMode);
    return () => document.body.classList.remove("demo-mode");
  }, [demoMode]);

  // ─── COMPUTED ───────────────────────────────────────────────────────────────
  const searchResults = useMemo(() => {
    const queryLower = query.toLowerCase();
    const similarities = SIMILARITY_MAP[queryLower] || {};
    return cache
      .map((item) => ({ ...item, match: similarities[item.id] ?? 0.0 }))
      .sort((a, b) => b.match - a.match);
  }, [cache, query]);

  const bestMatch = searchResults[0];
  const candidate = result?.candidate;
  const hit       = result?.hit;

  const paretoResult = useMemo(() => computeParetoFrontier(cache), [cache]);

  const allEntriesForPareto = useMemo(() =>
    candidate ? [...cache, candidate] : cache,
    [cache, candidate]
  );

  const paretoWithCandidate = useMemo(() =>
    computeParetoFrontier(allEntriesForPareto),
    [allEntriesForPareto]
  );

  // SCALM decision (fixed threshold)
  const scalmThreshold = SIMILARITY_THRESHOLD;
  const scalmHit = (bestMatch?.match ?? 0) >= scalmThreshold;

  // SPARC decision (adaptive threshold)
  const sparcHit = (bestMatch?.match ?? 0) >= adaptiveThreshold;

  // ─── LOGGING ────────────────────────────────────────────────────────────────
  function addLog(message) {
    setLogs((prev) =>
      [`${new Date().toLocaleTimeString()} — ${message}`, ...prev].slice(0, 10)
    );
  }

  // ─── STEP ADVANCE ───────────────────────────────────────────────────────────
  function nextStep() {
    if (stepIndex === 0) {
      setStepIndex(1);
      setResult(null);
      addLog("📥 Query received. Generating semantic embedding.");
      return;
    }
    const next = Math.min(stepIndex + 1, steps.length - 1);
    setStepIndex(next);

    if (steps[next] === "embedding") {
      const domain = classifyDomain(query);
      setQueryDomain(domain);
      addLog(`🧠 Embedding generated. Domain: ${domain}`);
    }
    if (steps[next] === "search") {
      const vol = bestMatch?.volatility ?? 0.0;
      const thresh = computeAdaptiveThreshold(queryDomain, vol);
      setAdaptiveThreshold(thresh);
      addLog(`🔍 Search complete. Best similarity: ${(bestMatch?.match ?? 0).toFixed(3)}. Adaptive threshold: ${thresh.toFixed(3)}`);
    }
    if (steps[next] === "decision") {
      const matchScore = bestMatch?.match ?? 0;
      const isHit = matchScore >= adaptiveThreshold;
      setResult({ hit: isHit, matched: bestMatch, candidate: null });
      addLog(
        isHit
          ? `✅ CACHE HIT (sim ${matchScore.toFixed(3)} ≥ threshold ${adaptiveThreshold.toFixed(3)}) — cached response returned.`
          : `❌ CACHE MISS (sim ${matchScore.toFixed(3)} < threshold ${adaptiveThreshold.toFixed(3)}) — sending to LLM.`
      );
    }
    if (steps[next] === "inference") {
      if (!hit) {
        const predefined = CANDIDATE_ENTRIES[query];
        const newCandidate = predefined
          ? { ...predefined, response: LLM_RESPONSES[query]?.text ?? LLM_RESPONSES.default.text, embedding: [0.5, 0.3, -0.1, 0.4, 0.2, -0.3, 0.1, 0.5], domain: classifyDomain(query), hits: 0 }
          : { id: `C${cache.length + 1}`, query, response: LLM_RESPONSES.default.text, embedding: [0.5, 0.3, -0.1, 0.4, 0.2, -0.3, 0.1, 0.5], tokenSaving: Math.round(200 + Math.random() * 150), volatility: Math.round(Math.random() * 100) / 100, domain: classifyDomain(query), hits: 0 };
        setResult((prev) => ({ ...prev, candidate: newCandidate }));
        addLog(`🤖 LLM response generated. Candidate: ${newCandidate.id} (saving=${newCandidate.tokenSaving}, vol=${newCandidate.volatility?.toFixed(2)})`);
      }
    }
    if (steps[next] === "evaluation") {
      const tsr = candidate?.tokenSaving ?? 0;
      const vol = candidate?.volatility ?? 0;
      addLog(`📊 Evaluated: TSR=${tsr}, volatility=${vol.toFixed(2)}, domain=${classifyDomain(candidate?.query ?? query)}`);
      setShowDetailedMetrics(true);
      setSystemMetrics((prev) => {
        const totalQ = (prev?.total_queries ?? 0) + 1;
        const hits = (prev?.hits ?? 0) + (result?.hit ? 1 : 0);
        const misses = (prev?.misses ?? 0) + (result?.hit ? 0 : 1);
        const staleHits = (prev?.stale_hits ?? 0) + (vol > 0.5 ? 1 : 0);
        const tokensSaved = (prev?.tokens_saved ?? 0) + (result?.hit ? tsr : 0);
        const totalTokens = (prev?.total_tokens ?? 0) + tsr;
        return {
          total_queries: totalQ, hits, misses, stale_hits: staleHits, false_hits: 0,
          tokens_saved: tokensSaved, total_tokens: totalTokens,
          hit_rate: hits / totalQ,
          token_saving_ratio: totalTokens > 0 ? tokensSaved / totalTokens : 0,
          staleness_rate: hits > 0 ? staleHits / hits : 0,
          false_hit_rate: 0,
        };
      });
    }
    if (steps[next] === "pareto") {
      addLog(`🏔️ Pareto frontier: ${paretoWithCandidate.frontier.length} non-dominated entries.`);
    }
    if (steps[next] === "admission") {
      if (candidate) {
        const { frontier } = computeParetoFrontier([...cache, candidate]);
        const isAdmitted = frontier.some((x) => x.id === candidate.id);
        if (isAdmitted) {
          const { kept } = pruneByHypervolume(frontier, 5);
          setCache(kept);
          addLog(`✅ ${candidate.id} admitted — non-dominated, within budget.`);
        } else {
          addLog(`❌ ${candidate.id} rejected — dominated by an existing entry.`);
        }
      }
    }
    if (steps[next] === "complete") {
      addLog("✅ Cache updated. Simulation complete.");
    }
  }

  function reset() {
    setCache(INITIAL_CACHE);
    setStepIndex(0);
    setResult(null);
    setLogs([]);
    setShowDetailedMetrics(false);
    setSystemMetrics(null);
    setExpandedEntry(null);
  }

  // ─── FULL DEMO RUN ──────────────────────────────────────────────────────────
  function runFullDemo() {
    reset();
    const domain = classifyDomain(query);
    setQueryDomain(domain);
    setTimeout(() => setStepIndex(1), 100);
    setTimeout(() => setStepIndex(2), 500);
    setTimeout(() => {
      const queryLower = query.toLowerCase();
      const similarities = SIMILARITY_MAP[queryLower] || {};
      const bestMatchEntry = cache
        .map((item) => ({ ...item, match: similarities[item.id] ?? 0.0 }))
        .sort((a, b) => b.match - a.match)[0];
      const vol = bestMatchEntry?.volatility ?? 0.0;
      const thresh = computeAdaptiveThreshold(domain, vol);
      setAdaptiveThreshold(thresh);
      const isHit = (bestMatchEntry?.match ?? 0) >= thresh;

      if (isHit) {
        setResult({ hit: true, matched: bestMatchEntry, candidate: null });
        addLog("✅ CACHE HIT — response returned without LLM inference.");
        setStepIndex(3);
        setTimeout(() => setStepIndex(8), 700);
      } else {
        const predefined = CANDIDATE_ENTRIES[query];
        const newCandidate = predefined
          ? { ...predefined, response: LLM_RESPONSES[query]?.text ?? LLM_RESPONSES.default.text, embedding: [0.5, 0.3, -0.1, 0.4, 0.2, -0.3, 0.1, 0.5], domain: classifyDomain(query), hits: 0 }
          : { id: `C${cache.length + 1}`, query, response: LLM_RESPONSES.default.text, embedding: [0.5, 0.3, -0.1, 0.4, 0.2, -0.3, 0.1, 0.5], tokenSaving: 250, volatility: 0.15, domain: classifyDomain(query), hits: 0 };
        setResult({ hit: false, matched: bestMatchEntry, candidate: newCandidate });
        setStepIndex(3);
        setTimeout(() => setStepIndex(4), 500);
        setTimeout(() => setStepIndex(5), 900);
        setTimeout(() => setStepIndex(6), 1300);
        setTimeout(() => {
          setStepIndex(7);
          const { frontier } = computeParetoFrontier([...cache, newCandidate]);
          const { kept } = pruneByHypervolume(frontier, 5);
          setCache(kept);
          addLog(`✅ ${newCandidate.id} evaluated: ${frontier.some((x) => x.id === newCandidate.id) ? "admitted" : "rejected"}.`);
        }, 1700);
        setTimeout(() => setStepIndex(8), 2200);
      }
    }, 900);
  }

  function selectDemoQuery(demoQuery) {
    setSelectedDemoQuery(demoQuery);
    setQuery(demoQuery.text);
    const domain = classifyDomain(demoQuery.text);
    setQueryDomain(domain);
    setAdaptiveThreshold(computeAdaptiveThreshold(domain, 0.0));
    setStepIndex(0);
    setResult(null);
    setLogs([]);
    setShowDetailedMetrics(false);
    setSystemMetrics(null);
    addLog(`📝 Selected: "${demoQuery.text}" [${domain}]`);
  }

  // ─── RENDER ───────────────────────────────────────────────────────────────
  return (
    <div className="app">
      {/* ── TOPBAR ─────────────────────────────────────────────────────── */}
      <header className="topbar">
        <div>
          <p className="eyebrow">ICECCE 2026 · Research Demo</p>
          <h1>Pareto-Based Semantic Cache Management</h1>
          <p className="subtitle">
            SCALM baseline · SPARC (multi-objective Pareto admission) · Interactive research visualization
          </p>
        </div>
        <div style={{ display: "flex", flexDirection: "column", gap: 8, alignItems: "flex-end" }}>
          <div className="badge">SPARC · ICECCE 2026</div>
          <button
            onClick={() => { setDemoMode((v) => !v); setShowNarration(false); }}
            style={{
              fontSize: 11,
              fontWeight: 700,
              textTransform: "uppercase",
              letterSpacing: "0.06em",
              padding: "6px 12px",
              background: demoMode ? "var(--accent)" : "rgba(255,255,255,0.12)",
              color: "white",
              border: demoMode ? "none" : "1px solid rgba(255,255,255,0.3)",
              borderRadius: "var(--radius)",
              cursor: "pointer",
            }}
          >
            {demoMode ? "✓ Demo Mode ON" : "Demo Mode"}
          </button>
          {demoMode && (
            <button
              onClick={() => setShowNarration((v) => !v)}
              style={{
                fontSize: 11,
                padding: "4px 10px",
                background: "transparent",
                color: "rgba(255,255,255,0.7)",
                border: "1px solid rgba(255,255,255,0.25)",
                borderRadius: "var(--radius-sm)",
                cursor: "pointer",
              }}
            >
              {showNarration ? "Hide narration guide" : "Show narration guide"}
            </button>
          )}
        </div>
      </header>

      {/* ── SECTION NAV ─────────────────────────────────────────────────── */}
      <nav
        aria-label="Section navigation"
        style={{
          background: "var(--surface)",
          borderBottom: "1px solid var(--border)",
          padding: "0 5vw",
          display: "flex",
          gap: 0,
          overflowX: "auto",
        }}
      >
        {[
          ["#journey",  "① Query Journey"],
          ["#pareto",   "② Pareto Trade-off"],
          ["#compare",  "③ SCALM vs SPARC"],
          ["#cache",    "④ Cache State"],
        ].map(([href, label]) => (
          <a
            key={href}
            href={href}
            style={{
              display: "inline-block",
              padding: "11px 16px",
              fontSize: 12,
              fontWeight: 600,
              color: "var(--muted)",
              textDecoration: "none",
              borderBottom: "2px solid transparent",
              whiteSpace: "nowrap",
            }}
            onMouseEnter={(e) => { e.currentTarget.style.color = "var(--fg)"; }}
            onMouseLeave={(e) => { e.currentTarget.style.color = "var(--muted)"; }}
          >
            {label}
          </a>
        ))}
      </nav>

      <main>
        {/* Narration guide (demo mode) */}
        {demoMode && showNarration && (
          <NarrationGuide />
        )}

        {/* ══════════════════════════════════════════════════════════════════
            SECTION 1 — QUERY JOURNEY
        ══════════════════════════════════════════════════════════════════ */}
        <section id="journey" className="card" aria-label="Query journey simulation">
          <div className="section-heading">
            <div>
              <h2>① Query Journey</h2>
              <p>
                Follow a query through the semantic cache pipeline step by step.{" "}
                <span style={{ background: "#fef3c7", color: "#92400e", fontSize: 10, fontWeight: 700, padding: "1px 6px", borderRadius: 4, textTransform: "uppercase", letterSpacing: "0.05em" }}>
                  Illustrative simulation
                </span>
              </p>
            </div>
            <div style={{ display: "flex", gap: 8, flexShrink: 0 }}>
              <button onClick={runFullDemo} style={{ fontSize: 13 }}>▶ Run All</button>
              <button
                className="secondary"
                onClick={() => nextStep()}
                disabled={stepIndex === steps.length - 1}
                style={{ fontSize: 13 }}
              >
                {stepIndex === 0 ? "Start" : "Next Step →"}
              </button>
              <button className="secondary" onClick={reset} style={{ fontSize: 13 }}>Reset</button>
            </div>
          </div>

          {/* Query input */}
          <div className="query-row">
            <input
              className="query-input"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Enter a query…"
              aria-label="Query input"
            />
          </div>

          {/* Preset queries */}
          <div className="presets" role="group" aria-label="Demo queries">
            {DEMO_QUERIES.map((dq) => (
              <button
                key={dq.text}
                onClick={() => selectDemoQuery(dq)}
                className={selectedDemoQuery.text === dq.text ? "active" : ""}
                title={dq.note}
              >
                {dq.text}
                <small>{dq.expectedHit ? "✓ HIT" : "✗ MISS"}</small>
              </button>
            ))}
          </div>

          {/* Pipeline stepper */}
          <div className="flow" role="list" aria-label="Processing pipeline steps">
            {STEP_LABELS.map(({ key, title, type, desc }, i) => {
              const stepIdx = steps.indexOf(key);
              const isActive = step === key;
              const isDone   = stepIdx < stepIndex;
              return (
                <React.Fragment key={key}>
                  <div
                    className={`flow-node ${isActive || isDone ? "active" : ""} ${type === "PROPOSED" ? "proposed" : ""}`}
                    role="listitem"
                    title={desc}
                    aria-current={isActive ? "step" : undefined}
                  >
                    <span className="node-number">{i + 1}</span>
                    <strong>{title}</strong>
                    <small>{type}</small>
                    {isActive && (
                      <small style={{ color: "var(--accent)", fontSize: 9, marginTop: 2 }}>● Active</small>
                    )}
                  </div>
                  {i < STEP_LABELS.length - 1 && <span className="arrow" aria-hidden="true">→</span>}
                </React.Fragment>
              );
            })}
          </div>

          {/* Two-column grid: Cache layer + Evaluation */}
          <div className="grid" style={{ marginTop: 16 }}>
            {/* ── Cache layer ─────────────────────────────────────────── */}
            <div>
              <h3 style={{ margin: "0 0 12px", fontSize: 13, fontWeight: 600, color: "var(--muted)", textTransform: "uppercase", letterSpacing: "0.06em" }}>
                Semantic Cache Layer
              </h3>

              {/* Decision comparison: SCALM vs SPARC */}
              <div className="decision-compare">
                <div className="decision-col scalm">
                  <div className="decision-label">SCALM (baseline)</div>
                  <div style={{ fontSize: 11, color: "var(--muted)", marginBottom: 4 }}>
                    Fixed threshold {scalmThreshold.toFixed(2)}
                  </div>
                  <div className={`decision-outcome ${stepIndex >= 3 ? (scalmHit ? "hit" : "miss") : ""}`}>
                    {stepIndex >= 3 ? (scalmHit ? "✅ HIT" : "❌ MISS") : "—"}
                  </div>
                </div>
                <div className="decision-col pareto">
                  <div className="decision-label">SPARC (proposed)</div>
                  <div style={{ fontSize: 11, color: "var(--muted)", marginBottom: 4 }}>
                    Adaptive threshold {adaptiveThreshold.toFixed(3)}
                  </div>
                  <div className={`decision-outcome ${stepIndex >= 3 ? (sparcHit ? "hit" : "miss") : ""}`}>
                    {stepIndex >= 3 ? (sparcHit ? "✅ HIT" : "❌ MISS") : "—"}
                  </div>
                </div>
              </div>

              {/* Status boxes */}
              <div className="cache-state">
                <div className={`state-box ${hit === true ? "hit" : hit === false ? "miss" : ""}`}>
                  <span>Cache Status</span>
                  <strong>{hit === true ? "HIT" : hit === false ? "MISS" : "WAITING"}</strong>
                </div>
                <div className="state-box">
                  <span>Best Similarity</span>
                  <strong>{bestMatch ? bestMatch.match.toFixed(3) : "—"}</strong>
                </div>
                <div className="state-box">
                  <span>Adaptive Threshold</span>
                  <strong>{adaptiveThreshold.toFixed(3)}</strong>
                  <small className="threshold-note">
                    base {SIMILARITY_THRESHOLD}{queryDomain !== "general" ? ` + ${queryDomain}` : ""}
                  </small>
                </div>
              </div>

              {/* Match list */}
              <div className="match-list" aria-label="Similarity scores">
                {searchResults.map((item) => (
                  <div className="match-row" key={item.id}>
                    <div>
                      <strong style={{ fontSize: 13 }}>{item.id}</strong>
                      <span style={{ marginLeft: 8, fontSize: 12 }}>{item.query}</span>
                      {item.domain && <span className="domain-badge" style={{ marginLeft: 6 }}>{item.domain}</span>}
                    </div>
                    <div className="similarity">
                      <span>{item.match.toFixed(3)}</span>
                      <div className="bar" role="meter" aria-valuenow={item.match} aria-valuemin={0} aria-valuemax={1}>
                        <i style={{ width: `${item.match * 100}%` }} />
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            </div>

            {/* ── Multi-objective evaluation ───────────────────────────── */}
            <div>
              <h3 style={{ margin: "0 0 12px", fontSize: 13, fontWeight: 600, color: "var(--muted)", textTransform: "uppercase", letterSpacing: "0.06em" }}>
                Multi-Objective Evaluation
              </h3>

              {candidate ? (
                <div className="candidate">
                  <div className="candidate-title">
                    <strong>{candidate.id}</strong>
                    <span>Candidate Cache Entry</span>
                    {candidate.domain && <span className="domain-badge">{candidate.domain ?? queryDomain}</span>}
                    <span className="volatility-badge">vol {candidate.volatility?.toFixed(2) ?? "0.00"}</span>
                  </div>

                  <div className="metrics">
                    <Metric label="Token Saving Proxy" value={candidate.tokenSaving} unit=" tokens" />
                    <Metric label="Volatility" value={candidate.volatility?.toFixed(2) ?? "0.00"} />
                    {showDetailedMetrics && (
                      <>
                        <Metric label="Hits" value={candidate.hits || 0} />
                        <Metric label="Domain" value={candidate.domain ?? queryDomain} />
                      </>
                    )}
                  </div>

                  {/* Volatility risk callout */}
                  {candidate.volatility > 0.4 && (
                    <div className="callout" style={{ marginTop: 10 }}>
                      ⚠ High volatility ({candidate.volatility?.toFixed(2)}) — this answer may go stale quickly.
                      Even with high token savings, SPARC will reject this candidate if a less volatile entry
                      with similar savings already exists.
                    </div>
                  )}

                  {/* System metrics (simulated session) */}
                  {showDetailedMetrics && systemMetrics && (
                    <div className="eval-metrics">
                      <h4>Session Metrics (simulated)</h4>
                      <div className="metrics">
                        <Metric label="Hit Ratio" value={(systemMetrics.hit_rate * 100).toFixed(1)} unit="%" />
                        <Metric label="Token Saving" value={(systemMetrics.token_saving_ratio * 100).toFixed(1)} unit="%" />
                        <Metric label="Staleness Rate" value={(systemMetrics.staleness_rate * 100).toFixed(1)} unit="%" />
                        <Metric label="False-Hit Rate" value={(systemMetrics.false_hit_rate * 100).toFixed(1)} unit="%" />
                      </div>
                    </div>
                  )}

                  {/* LLM response preview */}
                  {candidate.response && (
                    <div className="llm-response">
                      <strong>LLM Response (cached):</strong>
                      <p>{candidate.response}</p>
                    </div>
                  )}
                </div>
              ) : (
                <div className="empty">
                  <span>Waiting for a cache miss…</span>
                  <small>Choose a MISS query to see candidate evaluation.</small>
                </div>
              )}

              <div className="objective-key">
                <span>↑ Token saving — higher is better</span>
                <span>↓ Volatility — lower is safer</span>
              </div>
            </div>
          </div>

          {/* Activity log */}
          {!demoMode && (
            <details style={{ marginTop: 16 }} className="dev-only">
              <summary style={{ fontSize: 11, color: "var(--muted)", cursor: "pointer" }}>
                Activity Log ({logs.length} events)
              </summary>
              <div className="logs" aria-live="polite" aria-label="Activity log">
                {logs.length
                  ? logs.map((log, i) => <div key={i}>{log}</div>)
                  : <span>No activity yet.</span>}
              </div>
            </details>
          )}
        </section>

        {/* ══════════════════════════════════════════════════════════════════
            SECTION 2 — PARETO TRADE-OFF
        ══════════════════════════════════════════════════════════════════ */}
        <section id="pareto" className="card" aria-label="Pareto trade-off visualization">
          <div className="section-heading">
            <div>
              <h2>② Pareto Trade-off</h2>
              <p>
                Two competing objectives — <strong>no single winner</strong>. Each point is a cache candidate.
                The Pareto frontier (teal ●) contains entries where no competitor is better on <em>both</em> dimensions simultaneously.
              </p>
            </div>
            <div style={{ display: "flex", gap: 10, alignItems: "center", flexShrink: 0, fontSize: 11 }}>
              <span style={{ display: "flex", alignItems: "center", gap: 5 }}>
                <span style={{ width: 10, height: 10, borderRadius: "50%", background: "var(--pareto-color)", display: "inline-block" }} />
                Pareto frontier
              </span>
              <span style={{ display: "flex", alignItems: "center", gap: 5 }}>
                <span style={{ width: 10, height: 10, borderRadius: "50%", border: "1.5px solid var(--muted-2)", display: "inline-block" }} />
                Dominated
              </span>
              {candidate && (
                <span style={{ display: "flex", alignItems: "center", gap: 5 }}>
                  <span style={{ width: 10, height: 10, borderRadius: "50%", background: "var(--accent)", display: "inline-block" }} />
                  Candidate
                </span>
              )}
            </div>
          </div>

          <ParetoScatterChart
            frontier={paretoWithCandidate.frontier}
            dominated={paretoWithCandidate.dominated}
            candidate={candidate}
          />

          {/* Frontier list */}
          <div style={{ marginTop: 20 }}>
            <h3 style={{ margin: "0 0 10px", fontSize: 12, fontWeight: 700, textTransform: "uppercase", letterSpacing: "0.06em", color: "var(--muted)" }}>
              Non-dominated entries (Pareto frontier)
            </h3>
            <div className="frontier-list">
              {paretoWithCandidate.frontier.map((item) => (
                <div className="frontier-item" key={item.id}>
                  <strong>{item.id}</strong>
                  <span>Saving: {item.tokenSaving}</span>
                  <span>Volatility: {item.volatility?.toFixed(2) ?? "0.00"}</span>
                  <span>Hits: {item.hits || 0}</span>
                  {item.domain && <span>{item.domain}</span>}
                  <div className="frontier-badge">NON-DOMINATED</div>
                </div>
              ))}
            </div>
            {paretoWithCandidate.dominated.length > 0 && (
              <div className="frontier-list" style={{ marginTop: 8 }}>
                {paretoWithCandidate.dominated.map((item) => (
                  <div className="dominated-item frontier-item" key={item.id}>
                    <strong>{item.id}</strong>
                    <span>Saving: {item.tokenSaving}</span>
                    <span>Volatility: {item.volatility?.toFixed(2) ?? "0.00"}</span>
                    <div style={{ marginLeft: "auto", fontSize: 9, fontWeight: 700, textTransform: "uppercase", color: "var(--muted)" }}>
                      DOMINATED
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>
        </section>

        {/* ══════════════════════════════════════════════════════════════════
            SECTION 3 — SCALM vs SPARC COMPARISON (live backend)
        ══════════════════════════════════════════════════════════════════ */}
        <section id="compare" className="card" aria-label="SCALM vs SPARC backend comparison">
          <div className="section-heading">
            <div>
              <h2>③ SCALM vs SPARC</h2>
              <p>
                Run a full experiment against the real backend. Results are measured — not simulated.
                Requires the backend server at <code style={{ fontFamily: "var(--mono)", fontSize: 11, background: "var(--surface)", padding: "1px 5px" }}>http://localhost:8000</code>.
              </p>
            </div>
          </div>
          <ExperimentSection theme={theme} />
        </section>

        {/* ══════════════════════════════════════════════════════════════════
            SECTION 4 — CACHE STATE
        ══════════════════════════════════════════════════════════════════ */}
        <section id="cache" className="card" aria-label="Cache state">
          <div className="section-heading">
            <div>
              <h2>④ Cache State</h2>
              <p>Entries currently held in the cache after Pareto-based admission and eviction.</p>
            </div>
            <div className="cache-stats">
              <span>Total: {cache.length}</span>
              <span style={{ color: "var(--pareto-color)" }}>Pareto: {paretoResult.frontier.length}</span>
              <span style={{ color: "var(--muted-2)" }}>Dominated: {paretoResult.dominated.length}</span>
            </div>
          </div>

          <div className="cache-table">
            {cache.map((item) => {
              const isPareto = paretoResult.frontier.some((f) => f.id === item.id);
              const isExpanded = expandedEntry === item.id;
              return (
                <div
                  key={item.id}
                  className="cache-entry"
                  style={{ flexDirection: "column", alignItems: "stretch", cursor: "pointer" }}
                  onClick={() => setExpandedEntry(isExpanded ? null : item.id)}
                  role="button"
                  aria-expanded={isExpanded}
                  tabIndex={0}
                  onKeyDown={(e) => e.key === "Enter" && setExpandedEntry(isExpanded ? null : item.id)}
                >
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", gap: 12 }}>
                    <div style={{ minWidth: 0 }}>
                      <strong>{item.id}</strong>
                      <span style={{ display: "block", fontSize: 12, color: "var(--muted)", marginTop: 2, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                        {item.query}
                      </span>
                      {item.domain && <span className="domain-badge" style={{ marginTop: 4 }}>{item.domain}</span>}
                    </div>
                    <div style={{ display: "flex", alignItems: "center", gap: 8, flexShrink: 0 }}>
                      <span className="hits-badge">Hits: {item.hits || 0}</span>
                      <span className={`tag ${isPareto ? "pareto" : "dominated"}`}>
                        {isPareto ? "PARETO" : "DOMINATED"}
                      </span>
                      <span style={{ fontSize: 11, color: "var(--muted-2)" }}>{isExpanded ? "▲" : "▼"}</span>
                    </div>
                  </div>

                  {/* Volatility bar */}
                  <div style={{ display: "flex", alignItems: "center", gap: 8, marginTop: 6 }}>
                    <span style={{ fontSize: 10, color: "var(--muted)", minWidth: 56 }}>
                      Vol {item.volatility?.toFixed(2)}
                    </span>
                    <VolatilityBar value={item.volatility} />
                    <span style={{ fontSize: 10, color: "var(--muted)" }}>
                      Saving: {item.tokenSaving}
                    </span>
                  </div>

                  {/* Expanded detail */}
                  {isExpanded && (
                    <div style={{ marginTop: 10, paddingTop: 10, borderTop: "1px solid var(--border)", fontSize: 12 }}>
                      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 8 }}>
                        <div>
                          <span style={{ color: "var(--muted)", fontSize: 10, textTransform: "uppercase", letterSpacing: "0.05em" }}>Pareto Status</span>
                          <div style={{ fontWeight: 600, color: isPareto ? "var(--pareto-color)" : "var(--muted)" }}>
                            {isPareto ? "Non-dominated" : "Dominated"}
                          </div>
                        </div>
                        <div>
                          <span style={{ color: "var(--muted)", fontSize: 10, textTransform: "uppercase", letterSpacing: "0.05em" }}>Admission</span>
                          <div style={{ fontWeight: 600 }}>
                            {isPareto ? "✅ Retained" : "⚠ Would be evicted next"}
                          </div>
                        </div>
                      </div>
                      {item.response && (
                        <div className="llm-response" style={{ marginTop: 10 }}>
                          <strong>Cached response:</strong>
                          <p>{item.response.slice(0, 180)}{item.response.length > 180 ? "…" : ""}</p>
                        </div>
                      )}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        </section>
      </main>

      <footer>
        <span>SCALM semantic cache baseline</span>
        <span>·</span>
        <span>SPARC — Pareto multi-objective admission (2 objectives: TSR, volatility)</span>
        <span>·</span>
        <span>Adaptive threshold · Hypervolume-constrained eviction</span>
        <span>·</span>
        <span>ICECCE 2026</span>
      </footer>
    </div>
  );
}

export default App;
